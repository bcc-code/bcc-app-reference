// Writes a database in a running Postgres container as the snapshot files the AppHost restores
// (called by update.mjs). Postgres runs init files in sorted order, so the names carry the order:
//   000-schema.sql                CREATE DATABASE + pg_dump --section=pre-data
//   100-<schema>.<table>.sql      one COPY per table with rows, ordered by the primary key
//   800-sequences.sql             setval for every sequence
//   900-post-data.sql             indexes, constraints, foreign keys, triggers
// Constraints come last, so the data files need no order between tables. Each file is small enough for DCP to copy into a
// container, and the rows are ordered, so a regeneration only differs where the data does.
import { spawn, spawnSync } from 'node:child_process'
import { createWriteStream, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// DCP refuses to copy a larger file into a container.
const MAX_FILE_BYTES = 52_428_800

// Tables whose definition is kept and whose rows are never committed: sign-in sessions and the Data Protection key ring are
// secrets of one running instance.
const SKIPPED_TABLES = ['public.auth_sessions', 'public.data_protection_keys']

export async function writeSnapshot({ container, database, target }) {
  const header = '-- Generated by tools/db-snapshot/update.mjs. Do not edit.\n'
  const connect = `\\connect "${database}"\n`

  // The statement goes in on stdin, so no argument quoting is involved. onData streams the output.
  function psql(sql, onData) {
    const args = ['exec', '-i', container, 'psql', '-U', 'postgres', '-d', database, '-X', '-q', '-A', '-t', '-v', 'ON_ERROR_STOP=1']
    const child = spawn('docker', args, { stdio: ['pipe', 'pipe', 'pipe'] })
    let error = ''
    const chunks = []
    child.stderr.on('data', (d) => (error += d))
    child.stdout.on('data', (d) => (onData ? onData(d) : chunks.push(d)))
    child.stdin.end(sql)
    return new Promise((resolve, reject) => {
      child.on('exit', (code) =>
        code === 0
          ? resolve(Buffer.concat(chunks).toString('utf8').trim())
          : reject(new Error(`psql failed: ${error}\n${sql.slice(0, 300)}`)),
      )
    })
  }

  // pg_dump 18 writes a random \restrict key per run, which psql does not need. The version comments change with every minor
  // release of the image, so they go too.
  function pgDump(section) {
    const result = spawnSync(
      'docker',
      ['exec', container, 'pg_dump', '-U', 'postgres', '--no-owner', '--no-privileges', `--section=${section}`, database],
      { encoding: 'utf8', maxBuffer: 1024 * 1024 * 1024 },
    )
    if (result.status !== 0) throw new Error(`pg_dump failed: ${result.stderr}`)
    return result.stdout
      .split('\n')
      .filter((line) => !/^\\(un)?restrict /.test(line) && !/^-- Dumped (from|by) /.test(line))
      .join('\n')
  }

  const safe = (name) => name.replace(/[^A-Za-z0-9_.-]/g, '_')

  mkdirSync(target, { recursive: true })
  for (const old of readdirSync(target)) if (old.endsWith('.sql')) rmSync(join(target, old))

  writeFileSync(join(target, '000-schema.sql'), header + `CREATE DATABASE "${database}";\n` + connect + pgDump('pre-data'))

  // Columns as pg_dump lists them (no generated ones), and the primary key to order by.
  const tables = JSON.parse(
    await psql(`select coalesce(json_agg(t), '[]'::json) from (
  select format('%I.%I', n.nspname, c.relname) as qname, n.nspname as schema, c.relname as name,
    (select json_agg(quote_ident(a.attname) order by a.attnum) from pg_attribute a
      where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped and a.attgenerated = '') as cols,
    (select json_agg(quote_ident(a.attname) order by k.ord) from pg_index i
      cross join unnest(i.indkey::int2[]) with ordinality k(attnum, ord)
      join pg_attribute a on a.attrelid = c.oid and a.attnum = k.attnum
      where i.indrelid = c.oid and i.indisprimary) as pk
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where c.relkind in ('r', 'p') and not c.relispartition
    and n.nspname not in ('pg_catalog', 'information_schema') and n.nspname not like 'pg_toast%'
    -- The OIDC mock keeps its own database objects, if it ever gets any: never committed.
    and n.nspname <> 'oidcmock'
  order by 2, 3) t`),
  )

  let fileCount = 4
  for (const t of tables) {
    if (SKIPPED_TABLES.includes(`${t.schema}.${t.name}`)) continue
    const cols = t.cols.join(', ')
    // Without a primary key, every column; as text because some types (json) have no ordering.
    const order = (t.pk ?? t.cols.map((c) => `${c}::text`)).join(', ')
    const total = Number(await psql(`select count(*) from ${t.qname}`))
    if (total === 0) continue

    const name = safe(`100-${t.schema}.${t.name}.sql`)
    const out = createWriteStream(join(target, name))
    out.write(header + connect + `COPY ${t.qname} (${cols}) FROM stdin;\n`)
    let rows = 0
    await psql(`copy (select ${cols} from ${t.qname} order by ${order}) to stdout`, (data) => {
      // COPY text format escapes newlines inside values, so one line is one row.
      for (const byte of data) if (byte === 10) rows++
      out.write(data)
    })
    out.write('\\.\n')
    await new Promise((resolve) => out.end(resolve))
    if (rows !== total) throw new Error(`${t.qname}: wrote ${rows} rows to ${name}, count(*) is ${total}`)
    fileCount++
  }

  const setvals = await psql(
    `select format('SELECT pg_catalog.setval(%L, %s, true);', quote_ident(schemaname) || '.' || quote_ident(sequencename), last_value)
     from pg_sequences where last_value is not null order by schemaname, sequencename`,
  )
  writeFileSync(join(target, '800-sequences.sql'), header + connect + setvals + '\n')
  writeFileSync(join(target, '900-post-data.sql'), header + connect + pgDump('post-data'))

  let largest = { name: '', size: 0 }
  let totalSize = 0
  for (const name of readdirSync(target)) {
    const size = statSync(join(target, name)).size
    totalSize += size
    if (size > largest.size) largest = { name, size }
    if (size >= MAX_FILE_BYTES) {
      throw new Error(`${name} is ${size} bytes, over the ${MAX_FILE_BYTES} byte limit for copying into the container`)
    }
  }
  console.log(
    `Wrote ${fileCount} files, ${(totalSize / 1048576).toFixed(2)} MB; largest ${largest.name} (${(largest.size / 1048576).toFixed(2)} MB)`,
  )
}
